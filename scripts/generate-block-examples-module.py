"""Generate src/modBlockExamples.bas from the reviewed src/block-examples.json; never edit the module by hand.

Usage: python scripts/generate-block-examples-module.py [--check]
--check exits 1 when the module on disk differs from what the JSON produces.
"""
from pathlib import Path
import json
import re
import sys

root = Path(__file__).resolve().parents[1]
doc = json.loads((root / 'src/block-examples.json').read_text(encoding='utf-8'))
target = root / 'src/modBlockExamples.bas'
KINDS = ('EVAL', 'CHIEFEVAL', 'FITREP')


def literal(s):
    if any(ord(c) > 126 or ord(c) < 32 for c in s):
        raise ValueError('Non-ASCII or control character in an example: ' + repr(s[:60]))
    if len(s) > 800:
        raise ValueError('Example longer than 800 characters: ' + repr(s[:60]))
    return '"' + s.replace('"', '""') + '"'


def labels(key):
    # The three comment boxes of a CHIEFEVAL trait share their examples.
    m = re.fullmatch(r'(Trait3\d)Comment1', key)
    if m:
        return [f'{m.group(1)}Comment{i}' for i in (1, 2, 3)]
    return [key]


lines = ['Attribute VB_Name = "modBlockExamples"', 'Option Compare Database', 'Option Explicit',
         "' Generated by scripts/generate-block-examples-module.py from src/block-examples.json. Do not edit.",
         "' Sample entries the Block guide shows for a report field. A field's examples for the",
         "' report type come first; otherwise its examples for all types. Parts: 0 text, 1 note,",
         "' 2 source (EVALMAN or Swift), 3 the EVALMAN section title start for an EVALMAN example."]

keys = []
lines += ['Private Function Examples(ByVal key As String, ByVal kind As String) As Variant',
          '    Examples = Array()',
          '    Select Case key']
for key, entry in doc['examples'].items():
    for k in entry:
        if k != 'all' and k not in KINDS:
            raise ValueError(f'{key}: unknown report type {k}')
    keys += labels(key)
    lines.append('    Case ' + ', '.join(literal(k) for k in labels(key)))
    lines.append('        Select Case kind')
    order = [k for k in KINDS if k in entry] + (['all'] if 'all' in entry else [])
    for k in order:
        rows = []
        for e in entry[k]:
            if e['source'] not in ('EVALMAN', 'Swift'):
                raise ValueError(f'{key}: source must be EVALMAN or Swift')
            if e['source'] == 'EVALMAN' and not e.get('section'):
                raise ValueError(f'{key}: an EVALMAN example needs its section')
            rows.append('Array(' + ', '.join(literal(e.get(p, '')) for p in ('text', 'note', 'source', 'section')) + ')')
        lines.append('        Case ' + ('Else' if k == 'all' else literal(k)))
        lines.append('            Examples = Array(' + ', '.join(rows) + ')')
    lines.append('        End Select')
lines += ['    End Select', 'End Function', '',
          'Public Function BlockExampleCount(ByVal key As String, ByVal kind As String) As Long',
          '    BlockExampleCount = UBound(Examples(key, kind)) + 1',
          'End Function', '',
          'Public Function BlockExample(ByVal key As String, ByVal kind As String, ByVal index As Long, ByVal part As Long) As String',
          '    BlockExample = Examples(key, kind)(index)(part)',
          'End Function', '',
          "' Every field key that has examples, separated by commas, for tests.",
          'Public Function BlockExampleKeys() As String',
          '    Dim t As String']
for i in range(0, len(keys), 8):
    lines.append('    t = t & ' + literal((',' if i else '') + ','.join(keys[i:i + 8])))
lines += ['    BlockExampleKeys = t',
          'End Function']

text = '\r\n'.join(lines) + '\r\n'
if '--check' in sys.argv:
    current = target.read_bytes().decode('cp1252') if target.exists() else ''
    if current != text:
        print('src/modBlockExamples.bas is out of date; run scripts/generate-block-examples-module.py')
        sys.exit(1)
    print('src/modBlockExamples.bas is current')
else:
    target.write_bytes(text.encode('cp1252'))
    print(f'Wrote {target} ({len(keys)} keys)')
