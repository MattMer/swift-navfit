"""Refresh the PDF compatibility view from canonical field definitions.
Native VBA is generated by apply-ux-field-catalogue.ps1 during the manifest build.
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def generate():
    definitions = json.loads((ROOT / 'src/field-definitions.json').read_text(encoding='utf-8-sig'))
    result = {}
    for kind in ('EVAL', 'CHIEFEVAL', 'FITREP'):
        rows = [dict(target=field['key'], **binding)
                for field in definitions['fields']
                for binding in field['bindings'][kind]['pdf']]
        rows.sort(key=lambda row: row.pop('ordinal'))
        result[kind] = rows
    (ROOT / 'src/pdf-field-map.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')

if __name__ == '__main__':
    generate()
