"""Generate the native mapping from the reviewed May-2025 XFA field catalogue."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def rows(pairs, conversion="text"):
    return [{"target": target, "source": source, "conversion": conversion}
            for target, source in pairs]


common = rows([
    ("OfficialName", "a"), ("RankRate", "b"), ("Designator", "c"),
    ("MemberSSN", "d"), ("UnitUIC", "f"), ("ShipStation", "g"),
    ("ReportingSeniorName", "q"), ("ReportingSeniorGrade", "r"),
    ("ReportingSeniorDesignator", "s"), ("ReportingSeniorTitle", "t"),
    ("ReportingSeniorUIC", "v"), ("ReportingSeniorSSN", "w"),
    ("CommandEmployment", "x"), ("PrimaryDuty", "y"), ("DutyDescription", "z"),
    ("CounselorName", "_2"), ("AssignmentRecommendationA", "F"),
    ("AssignmentRecommendationB", "G"), ("OfficialComments", "H"),
    ("BilletSubcategory", "_21_Billet"),
]) + rows([("PeriodStart", "k"), ("PeriodEnd", "l")], "date") + rows([
    ("DateReported", "i"), ("CounselingDate", "_1")], "date-text") + rows([
    (f"Trait{33+i}", source) for i, source in enumerate(["_5", "_6", "_7", "_8", "_9", "D", "E"])], "trait") + rows([
    ("PromotionRecommendation", "I")], "recommendation")
component = rows([("ComponentActive", "e"), ("ComponentTAR", "e"),
                  ("ComponentInactive", "e"), ("ComponentATADSW", "e")], "component")
chief = rows([
    ("OfficialName", "NAMEmaster"), ("RankRate", "RATINGmaster"),
    ("Designator", "DESIGNATIONmaster"), ("MemberSSN", "SSNDODIDmaster"),
    ("UnitUIC", "UIC"), ("ShipStation", "SHIPSTATION"),
    ("ReportingSeniorName", "REPORTINGSENIOR"), ("ReportingSeniorGrade", "GRADE"),
    ("ReportingSeniorDesignator", "DESIGNATION"), ("ReportingSeniorTitle", "TITLE"),
    ("ReportingSeniorUIC", "REPORTINGUIC"), ("ReportingSeniorSSN", "SSN"),
    ("CounselorName", "COUSELOR"), ("PrimaryDuty", "WATCHSTANDING"),
    ("CommandEmployment", "COMMANDEMPLOY"), ("DutyDescription", "PRIMARYSTATEMENT"), ("OfficialComments", "REPORTINGSENIORCOMMENTS"),
    ("PromotionStatus", "PROMOTIONSTATUS"), ("PromotionRecommendation", "PROMOTIONDROPDOWN"),
    ("BilletSubcategory", "BILLETSUB"), ("AssignmentRecommendationA", "RECOMMENDATIONS1"),
    ("AssignmentRecommendationB", "RECOMMENDATIONS2"),
    ("ReportingSeniorAddress1", "Addressline1"), ("ReportingSeniorAddress2", "Addressline2"),
    ("ReportingSeniorPhone", "CommandPhoneCommercial"), ("ReportingSeniorDSN", "CommandPhoneDSN"),
]) + rows([("PeriodStart", "FromDate"), ("PeriodEnd", "ToDate")], "date") + rows([
    ("DateReported", "DATEREPORTED"), ("CounselingDate", "COUNSELDATE"), ("ReadinessDate", "PRTDate")], "date-text") + rows([
    (target, source) for target, source in zip(
        ["ComponentActive", "ComponentTAR", "ComponentInactive", "ComponentATADSW",
         "OccasionPeriodic", "OccasionDetachment", "OccasionFrocking", "OccasionSpecial",
         "ReportRegular", "ReportConcurrent", "ReportOperationalCommander", "StatementYes", "StatementNo"],
        ["ACTCHECK", "TARCHECK", "INACTCHECK", "ATADSW265CHECK",
         "PERIODICCHECK", "DETACHINDCHECK", "DETACHRSCHECK", "SPECIALCHECK",
         "REGULARCHECK", "CONCURRENTCHECK", "OPSCDRCHECK", "INTEND", "NOTINTEND"])], "flag") + rows([
    ("ObservationStatus", "NOBCHECK")], "observation") + rows([
    (f"Trait{33+i}", source) for i, source in enumerate([
        "TECHDROPDOWN", "INSTITUTEDROPDOWN", "PROFFDROPDOWN", "INTEGDROPDOWN",
        "ACCOUNTDROPDOWN", "DECKPLATEDROPDOWN", "TEAMDROPDOWN"])], "chief-trait")
catalogue = {"EVAL": common + component + rows([("PromotionStatus", "_8_Promotion_Status")], "promotion-status") + rows([
    ("RaterName", "T"), ("SeniorRaterName", "O")]) + rows([("RaterDate", "U"), ("SeniorRaterDate", "P")], "date-text"),
             "FITREP": common + component + rows([("PromotionStatus", "h")]), "CHIEFEVAL": chief}

def generate():
    (ROOT / "src/pdf-field-map.json").write_text(json.dumps(catalogue, indent=2) + "\n", encoding="utf-8")
    lines = ['Attribute VB_Name = "modPDFMapping"', 'Option Compare Binary', 'Option Explicit',
             "' Generated by scripts/generate-pdf-map.py; reviewed source bindings in planning/PDF_IMPORT_R26.md.",
             'Public Function PDFMapRows(ByVal kind As String) As Collection',
             '    Dim result As New Collection', '    Select Case kind']
    for kind, mapping in catalogue.items():
        lines.append(f'        Case "{kind}"')
        lines += ['            result.Add "{target}|{source}|{conversion}"'.format(**r) for r in mapping]
    lines += ['        Case Else: Err.Raise vbObjectError + 4720, , "Unsupported PDF report type."',
              '    End Select', '    Set PDFMapRows = result', 'End Function',
              'Public Function PDFMappingCount(ByVal kind As String) As Long',
              '    PDFMappingCount = PDFMapRows(kind).Count', 'End Function', '']
    (ROOT / "src/modPDFMapping.bas").write_text("\n".join(lines), encoding="utf-8")
    print({kind: len(mapping) for kind, mapping in catalogue.items()})

if __name__ == "__main__":
    generate()
