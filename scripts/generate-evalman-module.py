"""Generate src/modEvalmanText.bas from the reviewed src/evalman.json; never edit the module by hand.

Each section's text is built in its own function from literals of at most 800 characters,
so no line or procedure exceeds VBA limits.
"""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
doc = json.loads((root / 'src/evalman.json').read_text(encoding='utf-8'))
sections = doc['sections']


def literal(s):
    if any(ord(c) > 126 or ord(c) < 32 for c in s):
        raise ValueError('Non-ASCII or control character in EVALMAN text: ' + repr(s[:60]))
    return '"' + s.replace('"', '""') + '"'


def chunks(text, size=800):
    for line_no, line in enumerate(text.split('\n')):
        if line_no:
            yield None  # line break
        for i in range(0, len(line), size):
            yield line[i:i + size]


lines = ['Attribute VB_Name = "modEvalmanText"', 'Option Compare Database', 'Option Explicit',
         "' Generated by scripts/generate-evalman-module.py from src/evalman.json. Do not edit.",
         'Public Function EvalmanSource() As String',
         'EvalmanSource = ' + literal(f"BUPERSINST 1610.10H {doc['change']} ({doc['changeDate']})"),
         'End Function',
         'Public Function EvalmanSourceFile() As String',
         'EvalmanSourceFile = ' + literal(doc['source'] + ' SHA-256 ' + doc['sourceSha256']),
         'End Function',
         'Public Function EvalmanCount() As Long',
         f'EvalmanCount = {len(sections)}',
         'End Function',
         "' Section header values: 0 level, 1 title, 2 printed page, 3 PDF page.",
         'Public Function EvalmanHeader(ByVal index As Long, ByVal column As Long) As Variant',
         'Dim values As Variant',
         'Select Case index']
for i, s in enumerate(sections):
    lines.append(f"Case {i}: values = Array({s['level']}, {literal(s['title'])}, {literal(s['page'])}, {s['pdfPage']})")
lines += ['Case Else: Err.Raise vbObjectError + 6941, "modEvalmanText.EvalmanHeader", "Choose an EVALMAN section."',
          'End Select', 'EvalmanHeader = values(column)', 'End Function',
          'Public Function EvalmanText(ByVal index As Long) As String', 'Select Case index']
for i in range(len(sections)):
    lines.append(f'Case {i}: EvalmanText = T{i:04d}()')
lines += ['Case Else: Err.Raise vbObjectError + 6941, "modEvalmanText.EvalmanText", "Choose an EVALMAN section."',
          'End Select', 'End Function']
for i, s in enumerate(sections):
    lines.append(f'Private Function T{i:04d}() As String')
    lines.append('Dim t As String')
    for part in chunks(s['text']):
        lines.append('t = t & vbCrLf' if part is None else 't = t & ' + literal(part))
    lines += [f'T{i:04d} = t', 'End Function']
with open(root / 'src/modEvalmanText.bas', 'w', encoding='utf-8', newline='') as out:
    out.write('\r\n'.join(lines) + '\r\n')
print(f"Generated {len(sections)} EVALMAN sections, {sum(len(s['text']) for s in sections)} characters")
