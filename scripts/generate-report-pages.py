"""Refresh page/block and geometry compatibility views from canonical definitions.
Native VBA is generated by apply-ux-field-catalogue.ps1 during the manifest build.
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def generate():
    definitions = json.loads((ROOT / 'src/field-definitions.json').read_text(encoding='utf-8-sig'))
    mapping = {kind: {field['key']: field['bindings'][kind]['page']
                      for field in definitions['fields'] if field['bindings'][kind]['page'] is not None}
               for kind in ('EVAL', 'CHIEFEVAL', 'FITREP')}
    (ROOT / 'src/report-page-map.json').write_text(json.dumps(mapping, indent=2) + '\n', encoding='utf-8')
    (ROOT / 'src/report-page-layout.json').write_text(json.dumps(definitions['fixedLayout'], indent=2) + '\n', encoding='utf-8')

if __name__ == '__main__':
    generate()
