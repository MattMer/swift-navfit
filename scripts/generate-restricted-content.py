"""Generate Access rule code from the reviewed restricted-content catalogue.

src/restricted-content.json is the source; src/modRestrictedRules.bas is generated and
committed. Run after editing the catalogue:
    .venv/Scripts/python.exe scripts/generate-restricted-content.py
"""
from pathlib import Path
import hashlib
import json
import re

root = Path(__file__).resolve().parents[1]
source = root / 'src/restricted-content.json'
raw = source.read_bytes()
data = json.loads(raw.decode('utf-8'))
KINDS = {'words', 'marking', 'pii', 'caps'}
SEVERITIES = {'Needs review', 'Information'}
BLOCKS = {'OfficialComments', 'CommandEmployment', 'DutyDescription', 'Qualifications'}


def literal(s):
    if any(ord(c) > 126 or ord(c) < 32 for c in s):
        raise ValueError('Catalogue text must be printable ASCII: ' + s)
    return '"' + s.replace('"', '""') + '"'


def check_term(term, kind, unless=False):
    if not term or '~' in term or '|' in term:
        raise ValueError('Invalid term: ' + repr(term))
    if unless and term.startswith('<'):
        # An unless term starting with < counts only before the match ("<screened ... for hypertension").
        term = term[1:]
    if kind != 'marking':
        if term != term.lower() or not re.fullmatch(r"[a-z0-9 *']+", term) or term.strip() != term or '  ' in term:
            raise ValueError('Word terms are lower-case words separated by single spaces: ' + repr(term))
        for word in term.split(' '):
            if '*' in word[:-1] or word == '*':
                raise ValueError('"*" may only end a word: ' + repr(term))


def chunks(text, size=180):
    return [text[i:i + size] for i in range(0, len(text), size)] or ['']


ids = set()
rules = []
matches = []
for index, rule in enumerate(data['rules']):
    rid = rule['id']
    if not re.fullmatch(r'RC-[A-Z0-9-]+', rid) or rid in ids or len(rid) > 40:
        raise ValueError('Invalid or duplicate rule ID: ' + rid)
    ids.add(rid)
    kind = rule.get('kind', 'words')
    if kind not in KINDS:
        raise ValueError('Unknown kind: ' + kind)
    if rule['severity'] not in SEVERITIES:
        raise ValueError('Unknown severity: ' + rule['severity'])
    blocks = rule.get('blocks', [])
    if any(b not in BLOCKS for b in blocks):
        raise ValueError('Unknown block in ' + rid)
    rules.append([rid, rule['title'], rule['cite'], str(rule.get('page', '')), str(rule.get('pdfPage', 0)), rule['excerpt'], rule['severity'], kind, '|'.join(blocks)])
    for match in rule['matches']:
        for term in match['terms']:
            check_term(term, kind)
        for term in match.get('near', []):
            check_term(term, 'words')
        for term in match.get('unless', []):
            check_term(term, 'words', unless=True)
        within = int(match.get('within', 0))
        if match.get('near') and not 1 <= within <= 12:
            raise ValueError('near needs within 1-12: ' + rid)
        matches.append([index, '~'.join(match['terms']), '~'.join(match.get('near', [])), within, '~'.join(match.get('unless', []))])

lines = ['Attribute VB_Name = "modRestrictedRules"', 'Option Explicit',
         "'Generated by scripts/generate-restricted-content.py from src/restricted-content.json. Do not edit.",
         'Public Function RestrictedCatalogueHash() As String',
         'RestrictedCatalogueHash = "' + hashlib.sha256(raw).hexdigest().upper() + '"',
         'End Function',
         'Public Function RestrictedCatalogueSource() As String',
         'RestrictedCatalogueSource = ' + literal(data['source']),
         'End Function',
         'Public Function RestrictedRuleCount() As Long', f'RestrictedRuleCount = {len(rules)}', 'End Function',
         "'Array(id, title, cite, page, pdfPage, excerpt, severity, kind, blocks)",
         'Public Function RestrictedRule(ByVal index As Long) As Variant', 'Select Case index']
for i, rule in enumerate(rules):
    lines.append(f'Case {i}: RestrictedRule = Array(' + ', '.join(map(literal, rule)) + ')')
lines += ['Case Else: Err.Raise vbObjectError + 9850, "modRestrictedRules.RestrictedRule", "Unknown restricted-content rule."',
          'End Select', 'End Function',
          'Public Function RestrictedMatchCount() As Long', f'RestrictedMatchCount = {len(matches)}', 'End Function',
          "'Array(rule index, terms, near terms, within, unless terms); terms are separated by ~",
          'Public Function RestrictedMatch(ByVal index As Long) As Variant',
          'Dim terms As String, near As String, unless As String', 'Select Case index']
for i, (rule_index, terms, near, within, unless) in enumerate(matches):
    lines.append(f'Case {i}')
    for name, text in (('terms', terms), ('near', near), ('unless', unless)):
        for part in chunks(text):
            if part:
                lines.append(f'{name} = {name} & ' + literal(part))
    lines.append(f'RestrictedMatch = Array({rule_index}&, terms, near, {within}&, unless)')
lines += ['Case Else: Err.Raise vbObjectError + 9850, "modRestrictedRules.RestrictedMatch", "Unknown restricted-content pattern."',
          'End Select', 'End Function']
for line in lines:
    if len(line) > 1000:
        raise ValueError('Generated VBA line too long')
(root / 'src/modRestrictedRules.bas').write_bytes(('\r\n'.join(lines) + '\r\n').encode('ascii'))
print(f'Generated {len(rules)} rules and {len(matches)} pattern groups')
