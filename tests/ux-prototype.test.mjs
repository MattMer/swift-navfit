import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fields} from '../prototype/fields.mjs';
import {initialState,clone,isDirty,validate,validDate,saveReport,previewBatch,applyBatch,routeState,sectionNames,traitAverage,groupAverage,previewChanges,applyChanges} from '../prototype/model.mjs';
let checks=0;
const check=(truth,message)=>{assert.ok(truth,message);checks++;};
const source=readFileSync(new URL('../src/modAdministration.bas',import.meta.url),'utf8');
const keys=[...source.split('DraftFieldKeys = Array(')[1].split('End Function')[0].matchAll(/"(\w+)"/g)].map(m=>m[1]);
check(fields.length===78,'All 78 saved fields are described');
check(new Set(fields.map(f=>f.key)).size===78,'Field keys unique');
assert.deepEqual(fields.map(f=>f.key),keys);checks++;
check(sectionNames.length===10,'Seven official sections plus three local sections');
check(fields.every(f=>f.section>=0&&f.section<=7),'Each field has one editable section');
const s=initialState(),r=s.reports[0],pending=clone(r.values);
check(Object.keys(validate(pending)).length===0,'Synthetic starting values valid');
check(!isDirty(r.values,pending),'Clean copy has no pending changes');
pending.DraftNotes='Changed pending value';
check(isDirty(r.values,pending),'Pending notes mark draft dirty');
check(r.values.DraftNotes===''&&r.revision===1,'Editing does not commit');
let result=saveReport(s,r.id,pending);
check(result.changed&&r.revision===2,'Explicit save creates one new revision');
check(r.values.DraftNotes===pending.DraftNotes,'Pending value retained');
check(s.recovery===null,'Committed checkpoint cleared');
check(saveReport(s,r.id,pending).changed===false&&r.revision===2,'No-op save creates no revision');
const bad=clone(pending);bad.PeriodStart='2026-02-30';bad.MemberSSN='123';bad.OfficialName='X'.repeat(28);
check(Object.keys(validate(bad)).length===3,'Date, identifier and length errors identified together');
const before=clone(r);result=saveReport(s,r.id,bad);
check(Object.keys(result.errors).length===3,'Invalid save reports errors');
assert.deepEqual(r,before);checks++;
check(validDate('2024-02-29')&&!validDate('2025-02-29'),'Leap year boundary');
check(validate({...pending,PeriodStart:'2026-10-01',PeriodEnd:'2026-09-30'}).PeriodEnd,'Reversed period rejected');
assert.throws(()=>saveReport(s,4,clone(s.reports[3].values)),/Reopen/);checks++;
check(routeState(s,s.reports[2])==='Review needs restart','Revision mismatch is shown as stale');
const nameParts=clone(pending);nameParts.MemberFirstName='CHANGED';saveReport(s,1,nameParts);
check(r.values.OfficialName===pending.OfficialName,'Name part edits do not overwrite full name');
assert.throws(()=>previewBatch(s,[1,4],'ShipStation','NEW UNIT'),/Reopen/);checks++;
const rows=previewBatch(s,[1,2],'ShipStation','NEW UNIT');
check(s.reports[0].values.ShipStation==='SYNTHETIC UNIT','Preview has no effects');
applyBatch(s,rows);
check(s.reports[0].values.ShipStation==='NEW UNIT'&&s.reports[1].values.ShipStation==='NEW UNIT','Apply changes every selected report');
check(routeState(s,s.reports[1])==='Review needs restart','Bulk changes stale linked saved review');
const stale=previewBatch(s,[1,2],'ShipStation','SECOND UNIT');saveReport(s,2,{...s.reports[1].values,DraftNotes:'Later save'});
const snapshot=clone(s);
assert.throws(()=>applyBatch(s,stale),/changed after preview/);checks++;
assert.deepEqual(s,snapshot);checks++;
assert.throws(()=>previewBatch(s,[1],'FormKind','FITREP'),/editable field/);checks++;
assert.throws(()=>previewBatch(s,[],'ShipStation','UNIT'),/Select reports/);checks++;
const blank=Object.fromEntries(fields.map(f=>[f.key,'']));blank.FormKind='EVAL';
check(Object.keys(validate(blank)).length===0,'Incomplete entries are distinct from invalid entries');
check(fields.filter(f=>f.legacyHidden).length===2,'Legacy DoD IDs retained but hidden');
check(fields.filter(f=>f.key.startsWith('Occasion')).every(f=>f.checkbox),'Occasion blocks use checkbox controls');
check(traitAverage(initialState().reports[0].values).value===3,'ITA calculated');
check(traitAverage({...pending,ObservationStatus:'NOB'}).value===null,'Whole-report NOB has no displayed ITA');
check(traitAverage({...pending,Trait33:'NOB',Trait34:''}).partial,'Partial trait context retained');
check(groupAverage(initialState(),1).value===3,'Saved group average calculated');
const multi=initialState();const changes=previewChanges(multi,[1,2],{ShipStation:'OTHER UNIT',UnitUIC:'12345'});
check(changes.length===4,'Multi-block report-section preview');
applyChanges(multi,changes);
check(multi.reports[0].revision===2&&multi.reports[1].revision===2,'Multi-block apply creates one revision per report');
check(multi.reports[0].values.ShipStation==='OTHER UNIT'&&multi.reports[0].values.UnitUIC==='12345','Both shared changes applied');
const multiStale=previewChanges(multi,[1,2],{ShipStation:'NEXT UNIT',UnitUIC:'54321'});
saveReport(multi,2,{...multi.reports[1].values,DraftNotes:'Later save'});const multiBefore=clone(multi);
assert.throws(()=>applyChanges(multi,multiStale),/changed after preview/);checks++;
assert.deepEqual(multi,multiBefore);checks++;
console.log(`PASS: ${checks} prototype model and field-coverage checks`);
